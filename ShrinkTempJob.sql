/****** Object:  Job [ShrinkTemp]    Script Date: 2. 1. 2024 16:22:49 ******/
BEGIN TRANSACTION
DECLARE @ReturnCode INT
SELECT @ReturnCode = 0
DECLARE @User NVARCHAR(100)=SYSTEM_USER
